#!/bin/bash
# Builds web/vouch-policy.js, the trading policy the journal page re-runs in the
# browser, from the same TypeScript the parity tests hold to the Python agent.
set -euo pipefail
cd "$(dirname "$0")/../cre/vouch-verifier"
export PATH="$HOME/.bun/bin:$PATH"
OUT=${1:-../../web/vouch-policy.js}
bun build web.ts --target=browser --format=iife --minify --outfile="$OUT.tmp" >/dev/null
{ echo "// GENERATED by scripts/build_web.sh from cre/vouch-verifier/check/policy.ts. Do not edit."; cat "$OUT.tmp"; } > "$OUT"
rm -f "$OUT.tmp"
echo "built $OUT ($(wc -c < "$OUT") bytes)"
